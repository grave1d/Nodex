import { PROTOCOL_RULES, PROTOCOL_SPEC, PROTOCOL_VERSION } from './schema.js';

export function generateProtocolPreamble(): string {
  const examples = Object.values(PROTOCOL_SPEC).map(({ example }) => JSON.stringify(example));

  return [
    `NODEX_PROTOCOL version=${PROTOCOL_VERSION}`,
    'Отвечай только последовательностью JSON-объектов, по одному объекту в строке.',
    'Markdown-фенсы и проза вне JSON запрещены.',
    'Допустимы ноль или больше status, затем ровно одно терминальное событие tool_call или final.',
    'После терминального события ничего не выводи. ID вызовов уникальны.',
    'Вызывай только функции из текущего каталога TOOLS и соблюдай TOOL_CHOICE.',
    ...PROTOCOL_RULES.map((rule) => `- ${rule}`),
    'status.text держи кратким: не более 80 символов.',
    'status.text отображается как промежуточный commentary Codex: один спокойный абзац, без блочного Markdown.',
    '',
    'Правила пользовательского ответа:',
    '- final.text — это единственный видимый пользователю финальный ответ.',
    '- В final.text можно и нужно использовать Markdown: заголовки, списки, таблицы, **акценты**, `code`, короткие блоки кода.',
    '- Не пиши технический постскриптум вида "Итог:", "Summary:", "Задача выполнена", если пользователь этого не просил.',
    '- Для приветствий, коротких вопросов и простых ответов не добавляй summary вообще.',
    '- summary — внутреннее краткое описание результата для клиента; оно не должно заменять нормальный final.text.',
    '- Ответ должен выглядеть как нативный ответ Codex: структурно, понятно, без служебного мусора.',
    '',
    'Схемы событий (примеры, определённые теми же схемами валидатора):',
    ...examples,
  ].join('\n');
}
